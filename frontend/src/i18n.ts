const MESSAGES: Record<Locale, Record<MessageKey, string>> = {
  "zh-CN": ZH,
  "en-US": EN,
};

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translate(
  locale: Locale,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  const template = MESSAGES[locale]?.[key] ?? ZH[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

// React hook：订阅 locale（切换时触发重渲染），返回稳定的 t 包装。
export function useI18n(): {
  locale: Locale;
  t: Translate;
  setLocale: (locale: Locale) => void;
} {
  const locale = useUIStore((state) => state.locale);
  const setLocale = useUIStore((state) => state.setLocale);
  // t 的身份只随 locale 变化：组件把 t 放进 useCallback/useEffect 依赖时
  // 不会因为每次渲染新建函数而反复执行。
  const t = useCallback<Translate>((key, vars) => translate(locale, key, vars), [locale]);
  return { locale, t, setLocale };
}

export function selectLocale(state: { locale: Locale }): Locale {
  return state.locale;
}
